func TestCalendarEventsMatchReference(t *testing.T) {
	expected := readReferenceEvents()
	actual := computeCalendarEvents(t)

	if len(expected) != len(actual) {
		t.Errorf("количество событий не совпадает: эталон %d, получено %d", len(expected), len(actual))
	}

	// Сравнение по позициям (список календаря отсортирован по дате)
	max := len(expected)
	if len(actual) > max {
		max = len(actual)
	}

	mismatches := 0
	for i := 0; i < max; i++ {
		hasExp := i < len(expected)
		hasGot := i < len(actual)
		exp, got := "", ""
		if hasExp {
			exp = expected[i]
		}
		if hasGot {
			got = actual[i]
		}
		if exp == got {
			continue
		}
		mismatches++
		if mismatches > 30 {
			continue
		}
		switch {
		case hasExp && hasGot:
			t.Errorf("событие #%d (позиция %d):\n  эталон:  %s\n  текущее: %s", i+1, i, exp, got)
		case hasExp:
			t.Errorf("событие #%d (позиция %d) отсутствует в текущем выводе:\n  эталон: %s", i+1, i, exp)
		default:
			t.Errorf("лишнее событие #%d (позиция %d):\n  текущее: %s", i+1, i, got)
		}
	}

	// Анализ расхождений как множеств — устойчив к перестановкам событий
	expCount := make(map[string]int)
	for _, e := range expected {
		expCount[e]++
	}
	gotCount := make(map[string]int)
	for _, e := range actual {
		gotCount[e]++
	}

	var missing, extra []string
	for e, n := range expCount {
		if gotCount[e] < n {
			missing = append(missing, e)
		}
	}
	for e, n := range gotCount {
		if expCount[e] < n {
			extra = append(extra, e)
		}
	}
	if len(missing) > 0 {
		t.Errorf("отсутствующие события (%d):\n%s", len(missing), strings.Join(missing, "\n"))
	}
	if len(extra) > 0 {
		t.Errorf("лишние события (%d):\n%s", len(extra), strings.Join(extra, "\n"))
	}

	if mismatches > 0 {
		t.Errorf("всего расхождений в списке событий: %d", mismatches)
	} else {
		t.Logf("список событий полностью совпадает (%d событий)", len(expected))
	}
}
